import { normalize } from "./usage.js";
import type { UsageMessage } from "./usage.js";

export interface PerformanceSummary {
  tps?: number;
  tpsEstimated?: boolean;
  /** Average time to first token, in milliseconds. */
  ttft?: number;
}

export interface FirstTokenObservation {
  messageID: string;
  sessionID: string;
  started: number;
  first: number;
}

export interface PerformanceEvent {
  type: string;
  data: unknown;
  id?: string;
  created?: number;
}

export interface StreamSample {
  time: number;
  bytes: number;
}

export const LIVE_WINDOW_MS = 2_000;
export const LIVE_MIN_SPAN_MS = 500;
export const LIVE_SAMPLE_MS = 100;
export const LIVE_MIN_TOKENS = 20;
export const LIVE_MIN_BATCHES = 3;
export const LIVE_EWMA_ALPHA = 0.35;
export const LIVE_BYTES_PER_TOKEN = 4;
/** Quiet streams need a server liveness check, not a maximum tool-wait duration. */
export const ACTIVITY_CHECK_MS = 60_000;

export type ReadActiveSessions = (signal: AbortSignal) => Promise<ReadonlySet<string>>;
export interface PerformanceOptions {
  retention?: number;
  monotonic?: () => number;
  active?: ReadActiveSessions | undefined;
}

/** Requires three merged batches; the first is a baseline, not newly generated bytes. */
export function estimatedLiveTps(samples: readonly StreamSample[]): number | undefined {
  if (samples.length < LIVE_MIN_BATCHES) return undefined;
  const first = samples[0]!;
  const last = samples[samples.length - 1]!;
  const duration = last.time - first.time;
  if (!Number.isFinite(duration) || duration < LIVE_MIN_SPAN_MS) return undefined;
  let bytes = 0;
  let time = first.time;
  for (const sample of samples) {
    if (!Number.isFinite(sample.time) || sample.time < time || !Number.isFinite(sample.bytes) || sample.bytes < 0) return undefined;
    if (sample.time > first.time) bytes += sample.bytes;
    time = sample.time;
  }
  if (!Number.isFinite(bytes) || bytes <= 0) return undefined;
  return (bytes / LIVE_BYTES_PER_TOKEN) / (duration / 1_000);
}

/** Time-based EWMA: elapsed time determines the weight, never delta count. */
export function smoothLiveTps(previous: number | undefined, raw: number, elapsed = LIVE_MIN_SPAN_MS): number {
  if (previous === undefined || !Number.isFinite(previous)) return raw;
  if (!Number.isFinite(elapsed) || elapsed <= 0) return previous;
  const alpha = 1 - (1 - LIVE_EWMA_ALPHA) ** (elapsed / LIVE_MIN_SPAN_MS);
  return previous * (1 - alpha) + raw * alpha;
}

interface ActiveStep {
  messageID: string;
  sessionID: string;
  started: number;
  first?: number;
  last?: number;
  streamed?: number;
  finishedAt?: number;
  reconciledAt?: number;
  /** Local monotonic age and revision guard for asynchronous activity snapshots. */
  checkedAt: number;
  revision: number;
  /** Server event watermark, compared only with other server timestamps. */
  latest: number;
  /** Inferred inactivity can be revoked by newer live activity during retention. */
  inactive?: boolean;
  /** All observable bytes for this response, including expired windows and the baseline. */
  bytes: number;
  samples: StreamSample[];
  bucketStarted?: number;
  observedAt?: number;
  liveTps?: number;
  liveDuration?: number;
  smoothedAt?: number;
  events: Set<string>;
}

interface RuntimeObservation extends FirstTokenObservation {
  expiresAt?: number;
}

export interface PreparedPerformance {
  tps?: number;
  ttftSum: number;
  ttftCount: number;
  historical: ReadonlyMap<string, number>;
}

export type PerformanceSubscribe = (listener: (event: PerformanceEvent) => void) => () => void;
export type PerformanceListener = (sessionID: string) => void;

const finite = (value: unknown): value is number => typeof value === "number" && Number.isFinite(value);

function historicalFirst(message: UsageMessage): number | undefined {
  const started = message.time?.created;
  if (!finite(started)) return undefined;
  for (const part of message.content ?? []) {
    if (part.type === "text") {
      if (part.text) return undefined;
      continue;
    }
    if (part.type === "reasoning") {
      if (!part.text) continue;
      const first = part.time?.created;
      return finite(first) && first >= started ? first - started : undefined;
    }
    if (part.type === "tool") {
      const first = part.time?.created;
      return finite(first) && first >= started ? first - started : undefined;
    }
  }
  return undefined;
}

/** Exact completed-run TPS and the average of only measurable TTFT samples. */
export function historicalPerformance(
  messages: Iterable<UsageMessage>,
  observations: Iterable<FirstTokenObservation> = [],
): PerformanceSummary {
  return performanceWithObservations(preparePerformance(messages), observations);
}

/** The immutable part of a snapshot is scanned once, then reused for stream updates. */
export function preparePerformance(messages: Iterable<UsageMessage>): PreparedPerformance {
  let output = 0;
  let duration = 0;
  let ttftSum = 0;
  let ttftCount = 0;
  const historical = new Map<string, number>();
  for (const message of messages) {
    if (message.type !== "assistant") continue;
    const created = message.time?.created;
    const streamed = message.time?.streamed;
    const tokens = normalize(message.tokens);
    const generated = tokens.output + tokens.reasoning;
    if (finite(created) && finite(streamed) && streamed > created && generated > 0) {
      output += generated;
      duration += streamed - created;
    }
    const sample = historicalFirst(message);
    if (sample !== undefined && finite(sample) && sample >= 0) {
      historical.set(message.id, sample);
      ttftSum += sample;
      ttftCount++;
    }
  }
  return { ...(duration > 0 ? { tps: output / (duration / 1_000) } : {}), ttftSum, ttftCount, historical };
}

function performanceWithObservations(
  prepared: PreparedPerformance, observations: Iterable<FirstTokenObservation>,
): PerformanceSummary {
  const observed = new Map<string, FirstTokenObservation>();
  for (const sample of observations) {
    if (finite(sample.started) && finite(sample.first) && sample.first >= sample.started) observed.set(sample.messageID, sample);
  }
  let ttft = prepared.ttftSum;
  let ttftSamples = prepared.ttftCount;
  for (const sample of observed.values()) {
    const old = prepared.historical.get(sample.messageID);
    if (old !== undefined) { ttft -= old; ttftSamples--; }
    ttft += sample.first - sample.started;
    ttftSamples++;
  }
  const result: PerformanceSummary = {};
  if (prepared.tps !== undefined) result.tps = prepared.tps;
  if (ttftSamples > 0) result.ttft = ttft / ttftSamples;
  return result;
}

/** Captures streaming performance for every session for one plugin lifetime. */
export class PerformanceMonitor {
  private active = new Map<string, ActiveStep>();
  private observed = new Map<string, RuntimeObservation>();
  private listeners = new Set<PerformanceListener>();
  private cleanupTimer: ReturnType<typeof setTimeout> | undefined;
  private synchronization: AbortController | undefined;
  private disposed = false;
  private readonly unsubscribe: (() => void) | undefined;
  private readonly retention: number;
  private readonly monotonic: () => number;
  private readonly readActive: ReadActiveSessions | undefined;

  constructor(subscribe?: PerformanceSubscribe, options: PerformanceOptions = {}) {
    this.retention = options.retention ?? 60_000;
    this.monotonic = options.monotonic ?? (() => performance.now());
    this.readActive = options.active;
    this.unsubscribe = subscribe?.(event => this.handle(event));
  }

  listen(listener: PerformanceListener) {
    if (this.disposed) return () => {};
    this.listeners.add(listener);
    return () => { this.listeners.delete(listener); };
  }

  dispose() {
    if (this.disposed) return;
    this.disposed = true;
    this.unsubscribe?.();
    this.synchronization?.abort();
    clearTimeout(this.cleanupTimer);
    this.cleanupTimer = undefined;
    this.listeners.clear();
    this.active.clear();
    this.observed.clear();
  }

  private key(sessionID: string, messageID: string) { return `${sessionID}\0${messageID}`; }

  private publish(sessionID: string) {
    for (const listener of this.listeners) listener(sessionID);
  }

  private deleteSession(sessionID: string) {
    for (const [key, step] of this.active) if (step.sessionID === sessionID) this.active.delete(key);
    for (const [key, sample] of this.observed) if (sample.sessionID === sessionID) this.observed.delete(key);
    this.scheduleCleanup();
  }

  private resetLive(step: ActiveStep) {
    step.samples = [];
    delete step.bucketStarted;
    delete step.observedAt;
    delete step.liveTps;
    delete step.liveDuration;
    delete step.smoothedAt;
  }

  private touch(step: ActiveStep, created?: number) {
    step.revision++;
    step.checkedAt = this.monotonic();
    if (finite(created)) step.latest = Math.max(step.latest, created);
    // A live event wins over an inactive snapshot taken just before it arrived.
    if (step.inactive) {
      delete step.finishedAt;
      delete step.inactive;
      const sample = this.observed.get(this.key(step.sessionID, step.messageID));
      if (sample) delete sample.expiresAt;
    }
  }

  private finish(step: ActiveStep, inactive = false) {
    if (step.finishedAt !== undefined && (inactive || !step.inactive)) return;
    step.finishedAt ??= this.monotonic();
    step.inactive = inactive;
    step.revision++;
    const key = this.key(step.sessionID, step.messageID);
    const sample = this.observed.get(key);
    if (sample) sample.expiresAt = step.finishedAt + this.retention;
    this.resetLive(step);
    this.publish(step.sessionID);
  }

  /** One shared, history-free read covers offscreen sessions too. Failures are not idle. */
  private async checkActivity(force = false) {
    if (this.disposed || !this.readActive) return;
    if (this.synchronization) {
      if (!force) return;
      this.synchronization.abort();
      this.synchronization = undefined;
    }
    const now = this.monotonic();
    const unfinished = [...this.active.values()].filter(step => step.finishedAt === undefined);
    if (!unfinished.length || (!force && !unfinished.some(step => now - step.checkedAt >= ACTIVITY_CHECK_MS))) return;
    // The endpoint is process-wide: use each read for every tracked unfinished step,
    // rather than issuing one request per staggered session deadline.
    const candidates = new Map(unfinished.map(step => [step, step.revision]));
    const request = new AbortController();
    this.synchronization = request;
    const signal = AbortSignal.any([request.signal, AbortSignal.timeout(5_000)]);
    let onAbort: () => void = () => {};
    try {
      // Also bound readers that fail to cooperate with cancellation.
      const active = await Promise.race([
        this.readActive(signal),
        new Promise<never>((_, reject) => {
          onAbort = () => reject(signal.reason);
          signal.addEventListener("abort", onAbort, { once: true });
          if (signal.aborted) onAbort();
        }),
      ]);
      if (this.disposed || signal.aborted || this.synchronization !== request) return;
      for (const [step, revision] of candidates) {
        if (this.active.get(this.key(step.sessionID, step.messageID)) !== step || step.revision !== revision) continue;
        if (!active.has(step.sessionID)) this.finish(step, true);
      }
    } catch { /* Preserve quiet tools/retries when server activity is unknown. */ }
    finally {
      signal.removeEventListener("abort", onAbort);
      request.abort();
      if (this.synchronization === request) {
        this.synchronization = undefined;
        for (const [step, revision] of candidates) {
          if (step.revision === revision) step.checkedAt = this.monotonic();
        }
        this.scheduleCleanup();
      }
    }
  }

  private prune() {
    const monotonic = this.monotonic();
    const changed = new Set<string>();
    for (const [key, step] of this.active) {
      if (step.finishedAt !== undefined && step.finishedAt + this.retention <= monotonic) {
        this.active.delete(key);
        changed.add(step.sessionID);
      } else if (step.observedAt !== undefined && monotonic - step.observedAt >= LIVE_WINDOW_MS) {
        this.resetLive(step);
        changed.add(step.sessionID);
      }
    }
    for (const [key, sample] of this.observed) {
      if (sample.expiresAt !== undefined && sample.expiresAt <= monotonic) {
        this.observed.delete(key);
        changed.add(sample.sessionID);
      }
    }
    return changed;
  }

  private scheduleCleanup() {
    clearTimeout(this.cleanupTimer);
    this.cleanupTimer = undefined;
    if (this.disposed) return;
    let next = Infinity;
    const monotonic = this.monotonic();
    const retain = Number.isFinite(this.retention) && this.retention >= 0;
    for (const step of this.active.values()) {
      if (retain && step.finishedAt !== undefined) next = Math.min(next, step.finishedAt + this.retention - monotonic);
      if (step.finishedAt === undefined && this.readActive && !this.synchronization) {
        next = Math.min(next, step.checkedAt + ACTIVITY_CHECK_MS - monotonic);
      }
      // Local monotonic age, never client epoch minus a remote event timestamp.
      if (step.observedAt !== undefined) next = Math.min(next, step.observedAt + LIVE_WINDOW_MS - monotonic);
    }
    for (const sample of this.observed.values()) {
      if (retain && sample.expiresAt !== undefined) next = Math.min(next, sample.expiresAt - monotonic);
    }
    if (!Number.isFinite(next)) return;
    this.cleanupTimer = setTimeout(() => {
      this.cleanupTimer = undefined;
      for (const sessionID of this.prune()) this.publish(sessionID);
      void this.checkActivity();
      this.scheduleCleanup();
    }, Math.max(0, Math.ceil(next)));
    this.cleanupTimer.unref?.();
  }

  handle(event: PerformanceEvent): boolean {
    if (this.disposed) return false;
    for (const sessionID of this.prune()) this.publish(sessionID);
    if (event.type === "server.connected") {
      // Delivery across a connection gap cannot share a throughput window.
      for (const step of this.active.values()) {
        this.resetLive(step);
        this.publish(step.sessionID);
      }
      void this.checkActivity(true);
      this.scheduleCleanup();
      return false;
    }
    const data = (event.data && typeof event.data === "object" ? event.data : {}) as {
      assistantMessageID?: unknown;
      sessionID?: unknown;
      started?: unknown;
      delta?: unknown;
      status?: { type?: unknown };
    };
    const sessionID = typeof data.sessionID === "string" ? data.sessionID : undefined;
    if (event.type === "session.deleted") {
      if (sessionID) this.deleteSession(sessionID);
      return false;
    }
    if (!sessionID) return false;
    if (["session.execution.succeeded", "session.execution.failed", "session.execution.interrupted", "session.idle"].includes(event.type)
      || (event.type === "session.status" && data.status?.type === "idle")) {
      for (const step of this.active.values()) {
        if (step.sessionID !== sessionID || !finite(event.created) || event.created < step.latest) continue;
        step.latest = event.created;
        this.finish(step);
      }
      this.scheduleCleanup();
      return false;
    }
    if (event.type === "session.execution.started"
      || (event.type === "session.status" && ["busy", "retry"].includes(String(data.status?.type)))) {
      for (const step of this.active.values()) {
        if (step.sessionID === sessionID && finite(event.created) && event.created >= step.latest) this.touch(step, event.created);
      }
      this.scheduleCleanup();
      return false;
    }
    const messageID = typeof data.assistantMessageID === "string" ? data.assistantMessageID : undefined;
    if (!messageID) return false;
    const key = this.key(sessionID, messageID);

    if (event.type === "session.step.started") {
      if (!finite(data.started)) return false;
      if (this.active.has(key)) return false;
      // A session's foreground steps are serial; missing endings must not accumulate
      // forever just because the same session continues to run later steps.
      for (const step of this.active.values()) {
        if (step.sessionID !== sessionID) continue;
        if (step.started > data.started) return false;
      }
      for (const step of this.active.values()) {
        if (step.sessionID !== sessionID) continue;
        step.latest = Math.max(step.latest, data.started);
        this.finish(step);
      }
      this.active.set(key, {
        messageID, sessionID, started: data.started, bytes: 0, samples: [], events: new Set(),
        checkedAt: this.monotonic(), revision: 0, latest: Math.max(data.started, finite(event.created) ? event.created : data.started),
      });
      this.scheduleCleanup();
      return false;
    }

    const step = this.active.get(key);
    if (!step) return false;
    if (event.type === "session.retry.scheduled" || (event.type.startsWith("session.tool.") && event.type !== "session.tool.input.delta")) {
      if (!finite(event.created) || event.created < step.latest) return false;
      if (event.type === "session.retry.scheduled") {
        delete step.finishedAt;
        delete step.inactive;
        delete step.reconciledAt;
        delete step.streamed;
        this.resetLive(step);
        const sample = this.observed.get(key);
        if (sample) delete sample.expiresAt;
      }
      this.touch(step, event.created);
      this.scheduleCleanup();
      return false;
    }
    if (event.type === "session.step.streamed") {
      if (!finite(event.created) || event.created < step.started) return false;
      if (step.streamed !== undefined && event.created <= step.streamed) return false;
      step.streamed = event.created;
      this.touch(step, event.created);
      this.scheduleCleanup();
      if (step.bytes > 0) this.publish(sessionID);
      return step.bytes > 0;
    }
    if (event.type === "session.step.ended" || event.type === "session.step.failed") {
      if (finite(event.created) && event.created < step.latest) return false;
      if (finite(event.created)) step.latest = event.created;
      this.finish(step);
      this.scheduleCleanup();
      return false;
    }
    if (event.type !== "session.text.delta" && event.type !== "session.reasoning.delta"
      && event.type !== "session.tool.input.delta") return false;
    if (typeof data.delta !== "string" || data.delta.length === 0 || !finite(event.created) || event.created < step.started) return false;
    if (step.last !== undefined && event.created < step.last) return false;
    if (event.id && step.events.has(event.id)) return false;
    if (step.finishedAt !== undefined && !step.inactive) return false;
    if (event.id) step.events.add(event.id);
    this.touch(step, event.created);
    if (step.reconciledAt !== undefined) {
      // A later delta means the snapshot did not represent the final stream.
      delete step.reconciledAt;
      const sample = this.observed.get(key);
      if (sample) delete sample.expiresAt;
      this.scheduleCleanup();
    }
    const sampleBytes = new TextEncoder().encode(data.delta).byteLength;
    step.bytes += sampleBytes;
    if (step.last !== undefined && event.created - step.last >= LIVE_WINDOW_MS) this.resetLive(step);
    const last = step.samples.at(-1);
    if (last && step.bucketStarted !== undefined && event.created - step.bucketStarted < LIVE_SAMPLE_MS) {
      // Include a whole delivery burst in one batch, including the initial baseline.
      last.time = event.created;
      last.bytes += sampleBytes;
    } else {
      step.bucketStarted = event.created;
      step.samples.push({ time: event.created, bytes: sampleBytes });
    }
    const cutoff = event.created - LIVE_WINDOW_MS;
    while (step.samples.length > 0 && step.samples[0]!.time < cutoff) step.samples.shift();
    // The response-wide threshold includes the baseline and survives window resets.
    const raw = step.bytes >= LIVE_MIN_TOKENS * LIVE_BYTES_PER_TOKEN ? estimatedLiveTps(step.samples) : undefined;
    if (raw === undefined) {
      delete step.liveTps;
      delete step.liveDuration;
      delete step.smoothedAt;
    } else if (step.smoothedAt === undefined || event.created - step.smoothedAt >= LIVE_SAMPLE_MS) {
      step.liveTps = smoothLiveTps(step.liveTps, raw, event.created - (step.smoothedAt ?? event.created));
      step.liveDuration = event.created - step.samples[0]!.time;
      step.smoothedAt = event.created;
    }
    step.observedAt = this.monotonic();
    step.last = Math.max(step.last ?? event.created, event.created);
    if (step.first === undefined) {
      step.first = event.created;
      this.observed.set(key, { messageID, sessionID, started: step.started, first: event.created });
    }
    this.scheduleCleanup();
    this.publish(sessionID);
    return true;
  }

  reconcile(messages: Iterable<UsageMessage>, sessionIDs: Iterable<string>) {
    const sessions = new Set(sessionIDs);
    if (this.disposed) return;
    const represented = new Map<string, UsageMessage>();
    for (const message of messages) {
      if (message.type === "assistant" && (message.tokens || message.time?.streamed !== undefined
        || message.time?.completed !== undefined)) represented.set(message.id, message);
    }
    for (const step of this.active.values()) {
      if (sessions.has(step.sessionID) && represented.has(step.messageID)) {
        // streamed/tokens describe the provider boundary, not tool settlement.
        // Only completion or an authoritative inactive session permits expiry;
        // a stale pre-retry completion cannot settle newer activity.
        step.reconciledAt ??= this.monotonic();
        const completed = represented.get(step.messageID)?.time?.completed;
        if (finite(completed) && completed >= step.latest) {
          step.latest = completed;
          this.finish(step);
        }
      }
    }
    this.scheduleCleanup();
  }

  summary(messages: Iterable<UsageMessage>, sessionIDs: Iterable<string>): PerformanceSummary {
    return this.summaryPrepared(preparePerformance(messages), sessionIDs);
  }

  summaryPrepared(prepared: PreparedPerformance, sessionIDs: Iterable<string>): PerformanceSummary {
    const sessions = new Set(sessionIDs);
    const samples = [...this.observed.values()].filter(sample => sessions.has(sample.sessionID));
    const result = performanceWithObservations(prepared, samples);
    // Live throughput covers only observable deltas after the first one, over a
    // short sliding window. TTFT keeps the started -> first wait separately, and
    // completed provider usage still replaces this estimate via reconcile().
    let weighted = 0;
    let durationTotal = 0;
    const monotonic = this.monotonic();
    for (const step of this.active.values()) {
      if (!sessions.has(step.sessionID) || step.reconciledAt !== undefined) continue;
      if (step.liveTps === undefined || step.observedAt === undefined
        || monotonic - step.observedAt >= LIVE_WINDOW_MS) continue;
      const duration = step.liveDuration;
      if (!finite(duration) || duration < LIVE_MIN_SPAN_MS) continue;
      weighted += step.liveTps * duration;
      durationTotal += duration;
    }
    if (durationTotal > 0) {
      result.tps = weighted / durationTotal;
      result.tpsEstimated = true;
    }
    return result;
  }
}
